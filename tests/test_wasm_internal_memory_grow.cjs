const assert = require('node:assert');

// (import "env" "probe" (func)) (memory (export "memory") 1 4)
// (func (export "growAndProbe") (drop (memory.grow (i32.const 1))) (call 0))
const growAndProbe = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x04, 0x01, 0x60, 0x00, 0x00,
  0x02, 0x0d, 0x01, 0x03, 0x65, 0x6e, 0x76, 0x05, 0x70, 0x72, 0x6f, 0x62, 0x65, 0x00, 0x00,
  0x03, 0x02, 0x01, 0x00,
  0x05, 0x04, 0x01, 0x01, 0x01, 0x04,
  0x07, 0x19, 0x02,
  0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00,
  0x0c, 0x67, 0x72, 0x6f, 0x77, 0x41, 0x6e, 0x64, 0x50, 0x72, 0x6f, 0x62, 0x65, 0x00, 0x01,
  0x0a, 0x0b, 0x01, 0x09, 0x00, 0x41, 0x01, 0x40, 0x00, 0x1a, 0x10, 0x00, 0x0b,
]);

// (memory (export "memory") 1 4) with an exported "grow" that runs memory.grow.
const growExport = new Uint8Array([
  0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
  0x01, 0x06, 0x01, 0x60, 0x01, 0x7f, 0x01, 0x7f,
  0x03, 0x02, 0x01, 0x00,
  0x05, 0x04, 0x01, 0x01, 0x01, 0x04,
  0x07, 0x11, 0x02,
  0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00,
  0x04, 0x67, 0x72, 0x6f, 0x77, 0x00, 0x00,
  0x0a, 0x08, 0x01, 0x06, 0x00, 0x20, 0x00, 0x40, 0x00, 0x0b,
]);

{
  const { exports } = new WebAssembly.Instance(new WebAssembly.Module(growExport));
  const before = exports.memory.buffer;
  const bytes = new Uint8Array(before);
  const words = new DataView(before);
  bytes[7] = 9;

  assert.strictEqual(exports.grow(2), 1);
  assert.strictEqual(before.byteLength, 0);
  assert.strictEqual(bytes.byteLength, 0);
  assert.strictEqual(bytes[7], undefined);
  assert.throws(() => words.getUint8(0), TypeError);

  const after = exports.memory.buffer;
  assert.notStrictEqual(after, before);
  assert.strictEqual(after.byteLength, 3 * 65536);
  assert.strictEqual(new Uint8Array(after)[7], 9);
}

{
  let seen = null;
  let view = null;
  let buffer = null;
  const { exports } = new WebAssembly.Instance(new WebAssembly.Module(growAndProbe), {
    env: {
      probe() {
        seen = { view: view.byteLength, buffer: buffer.byteLength, current: exports.memory.buffer.byteLength };
      },
    },
  });

  buffer = exports.memory.buffer;
  view = new Uint8Array(buffer);
  view[0] = 5;

  exports.growAndProbe();
  assert.deepStrictEqual(seen, { view: 0, buffer: 0, current: 2 * 65536 });
  assert.strictEqual(new Uint8Array(exports.memory.buffer)[0], 5);
}

console.log('wasm:internal-memory-grow:ok');
