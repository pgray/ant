const assert = require('node:assert');

function evalCase(N) {
  var evalVar = 1;
  function readEvalVar() { return evalVar; }
  let ev = 0;
  for (let i = 0; i < N; i++) ev += readEvalVar();
  (function () { eval('evalVar = 5'); })();
  return 'eval ' + ev + ' ' + readEvalVar();
}

function child() {
  const out = [];
  const N = 20000;

  function early() { return typeof LATE === 'undefined' ? 'u' : LATE; }
  for (let i = 0; i < N; i++) assert.strictEqual(early(), 'u');
  var LATE = 7;
  let lateSum = 0;
  for (let i = 0; i < N; i++) lateSum += early();
  out.push('late ' + lateSum);

  var STATE_A = 1, STATE_B = 2, MASK = ~4;
  function Task(s) { this.state = s; }
  Task.prototype.isA = function isA() { return (this.state & MASK) === STATE_A; };
  Task.prototype.flip = function () { this.state = this.state === STATE_A ? STATE_B : STATE_A; };
  const t = new Task(STATE_A);
  let flips = 0;
  for (let i = 0; i < N * 5; i++) { if (t.isA()) flips++; t.flip(); }
  out.push('flips ' + flips);

  var looped;
  const seen = [];
  for (let i = 0; i < 3; i++) {
    looped = i;
    seen.push(() => looped);
  }
  function readLooped() { return looped; }
  let ls = 0;
  for (let i = 0; i < N; i++) ls += readLooped();
  looped = 100;
  out.push('looped ' + ls + ' ' + readLooped() + ' ' + seen[0]());

  var later = 'a';
  function setLater(v) { later = v; }
  function readLater() { return later; }
  let ra = '';
  for (let i = 0; i < N; i++) ra = readLater();
  setLater('b');
  out.push('nested-write ' + ra + readLater());

  function make(v) {
    var K = v;
    return function get() { return K; };
  }
  const g1 = make(1);
  let s1 = 0;
  for (let i = 0; i < N * 3; i++) s1 += g1();
  const g2 = make(2);
  let s2 = 0;
  for (let i = 0; i < N * 3; i++) s2 += g2() + g1();
  out.push('closures ' + s1 + ' ' + s2);

  const C = { k: 3 };
  let L;
  L = 'once';
  class Shape { area() { return C.k; } }
  function useAll() { return C.k + L + new Shape().area(); }
  let ua = '';
  for (let i = 0; i < N; i++) ua = useAll();
  C.k = 4;
  out.push('const-object ' + ua + ' ' + useAll());

  out.push(evalCase(N));

  var counter = 0;
  function bump() { return counter; }
  for (let i = 0; i < N; i++) { counter = i; bump(); }
  out.push('loop-write ' + bump());

  function inner() { return TOP_FN() + 1; }
  function TOP_FN() { return 41; }
  let tf = 0;
  for (let i = 0; i < N; i++) tf = inner();
  out.push('fn ' + tf);

  console.log(out.join('\n'));
}

if (process.argv[2] === 'child') {
  child();
} else {
  const { spawnSync } = require('node:child_process');
  const base = { ...process.env };
  delete base.ANT_DEBUG;
  const run = (env, args = []) => spawnSync(process.execPath, [...args, __filename, 'child'], {
    encoding: 'utf8',
    env: { ...base, ...env, NO_COLOR: '1' },
    timeout: 120000, maxBuffer: 256 * 1024 * 1024,
  });
  const interp = run({}, ['--jitless']);
  assert.strictEqual(interp.status, 0, interp.stdout + interp.stderr);
  assert.strictEqual(interp.stdout, [
    'late 140000', 'flips 50000', 'looped 40000 100 100', 'nested-write ab',
    'closures 60000 180000', 'const-object 3once3 4once4', 'eval 20000 5', 'loop-write 19999', 'fn 42', '',
  ].join('\n'));
  const modes = [
    ['default', 'dump/vm:op-warn'],
    ['verify', 'opt:verify dump/vm:op-warn'],
    ['force', 'opt:force,verify dump/vm:op-warn'],
    ['off', 'opt:off dump/vm:op-warn'],
  ];
  for (const [name, debug] of modes) {
    const child = run({ ANT_DEBUG: debug });
    assert.strictEqual(child.status, 0, `${name}: ${child.error || child.stdout + child.stderr.slice(-4000)}`);
    assert.strictEqual(child.stdout, interp.stdout, `${name}: output differs from --jitless`);
    console.log(`PASS opt write-once upvalues ${name}`);
  }
  const tier = (process.arch === 'arm64' || process.arch === 'x64') && (process.platform === 'darwin' || process.platform === 'linux');
  if (tier) {
    const dumped = run({ ANT_DEBUG: 'dump/opt:graph' });
    assert.strictEqual(dumped.status, 0, `dump: ${dumped.error || dumped.stderr.slice(-4000)}`);
    const graphs = (fn) => dumped.stderr.split('[generated bytecode for function: ')
      .filter((g) => g.startsWith(fn + ' ') && g.includes('=== optimized'))
      .map((g) => g.split('=== optimized')[1].split('=== ')[0]);
    const isA = graphs('isA');
    assert.ok(isA.length >= 1, 'isA must compile');
    assert.doesNotMatch(isA[isA.length - 1], /LoadUpvalue/, 'constants written once must fold');
    const looped = graphs('readLooped');
    assert.ok(looped.length >= 1, 'readLooped must compile');
    assert.match(looped[looped.length - 1], /LoadUpvalue/, 'a binding written in a loop must stay a load');
    console.log('PASS opt write-once upvalues dump');
  }
}
