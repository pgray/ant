const assert = require('node:assert');

function child() {
  var Class = { create: function () { return function () { this.initialize.apply(this, arguments); }; } };
  var Ns = { K: {} };
  Ns.K.Color = Class.create();
  Ns.K.Color.prototype = {
    red: 0, green: 0, blue: 0,
    initialize: function (r, g, b) { this.red = r || 0; this.green = g || 0; this.blue = b || 0; },
    add: function (c1, c2) { var r = new Ns.K.Color(0, 0, 0); r.red = c1.red + c2.red; r.green = c1.green + c2.green; r.blue = c1.blue + c2.blue; return r; },
    scale: function (c1, f) { var r = new Ns.K.Color(0, 0, 0); r.red = c1.red * f; r.green = c1.green * f; r.blue = c1.blue * f; return r; },
    blend: function (c1, c2, w) { return Ns.K.Color.prototype.add(Ns.K.Color.prototype.scale(c1, 1 - w), Ns.K.Color.prototype.scale(c2, w)); },
  };
  var a = new Ns.K.Color(1, 2, 3), b = new Ns.K.Color(5, 6, 7), s = 0;
  for (var i = 0; i < 20000; i++) s += a.blend(a, b, (i & 7) / 8).green;
  console.log('blend', s);

  function make() { return { k: 2, m: function () { return this.k; } }; }
  var watched = make(), sibling = make();
  function readK(o) { return o.k; }
  var total = 0;
  for (var j = 0; j < 20; j++) total += readK(watched);
  var heir = Object.create(watched);
  function callM(o) { return o.m(); }
  for (var j = 0; j < 20000; j++) total += callM(heir);
  for (var j = 0; j < 20000; j++) total += readK(watched);
  total += readK(sibling);
  for (var j = 0; j < 20000; j++) total += readK(j & 1 ? watched : sibling);
  sibling.k = 3;
  for (var j = 0; j < 2000; j++) total += readK(j & 1 ? watched : sibling);
  console.log('sibling', total);
}

if (process.argv[2] === 'child') {
  child();
} else {
  const { spawnSync } = require('node:child_process');
  const base = { ...process.env };
  delete base.ANT_DEBUG;
  const run = (env, args = []) => spawnSync(process.execPath, [...args, __filename, 'child'], {
    encoding: 'utf8',
    env: { ...base, ...env, NO_COLOR: '1' },
    timeout: 120000, maxBuffer: 256 * 1024 * 1024,
  });
  const interp = run({}, ['--jitless']);
  assert.strictEqual(interp.status, 0, interp.stdout + interp.stderr);
  assert.match(interp.stdout, /^blend [\d.]+\nsibling \d+\n$/);
  const tier = (process.arch === 'arm64' || process.arch === 'x64') && (process.platform === 'darwin' || process.platform === 'linux');
  const modes = [
    ['default', 'dump/vm:op-warn'],
    ['verify', 'opt:verify dump/vm:op-warn'],
    ['force', 'opt:force,verify dump/vm:op-warn'],
    ['off', 'opt:off dump/vm:op-warn'],
  ];
  for (const [name, debug] of modes) {
    const child = run({ ANT_DEBUG: debug });
    assert.strictEqual(child.status, 0, `${name}: ${child.error || child.stdout + child.stderr.slice(-4000)}`);
    assert.strictEqual(child.stdout, interp.stdout, `${name}: output differs from --jitless`);
    if (tier && name !== 'off') assert.doesNotMatch(child.stderr, /opt disabled func=readK /, `${name}: a superseded shape must not disable the reader`);
    console.log(`PASS opt superseded shapes ${name}`);
  }
  if (tier) {
    const dumped = run({ ANT_DEBUG: 'dump/opt:graph dump/vm:op-warn' });
    assert.strictEqual(dumped.status, 0, `dump: ${dumped.error || dumped.stderr.slice(-4000)}`);
    const graphs = (fn) => dumped.stderr.split('[generated bytecode for function: ')
      .filter((g) => g.startsWith(fn + ' ') && g.includes('=== optimized'))
      .map((g) => g.split('=== optimized')[1].split('=== ')[0]);
    const blend = graphs('blend');
    assert.ok(blend.length >= 1, 'blend must compile');
    assert.doesNotMatch(blend[0], /NewThis|CheckClosure/, 'methods loaded from a watched prototype must be known values');
    assert.match(dumped.stderr, /func=readK .*kind=BadShape/, 'readK must exit when the sibling brings the superseded shape back');
    const readK = graphs('readK');
    assert.ok(readK.length >= 2, 'readK must recompile after its shape exit');
    assert.match(readK[readK.length - 1], /ShapeSwitch/, 'the recompile must keep the superseded shape');
    console.log('PASS opt superseded shapes dump');
  }
}
